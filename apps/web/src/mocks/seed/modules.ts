/**
 * Other tenants get their own version of the story. A string-level rewrite is enough for sample data
 * and keeps every tenant's content visibly different, which is what the isolation demo needs.
 */
export function retheme(modules: TenantModules, replacements: [string, string][]): TenantModules {
  let json = JSON.stringify(modules);
  for (const [from, to] of replacements) json = json.split(from).join(to);
  return JSON.parse(json) as TenantModules;
}
